import { useEffect, useState } from "react"
import { genai, type MatchInput, type Narrative } from "../lib/genai"

export default function MatchNarrative({
  match,
  answers,
}: {
  match: MatchInput
  answers: number[]
}) {
  const [data, setData] = useState<Narrative | null>(null)

  useEffect(() => {
    let alive = true
    setData(null)
    genai.narrative(match, answers).then((n) => alive && setData(n))
    return () => {
      alive = false
    }
  }, [match, answers])

  if (!data) {
    return (
      <div className="compatibility-box narrative-loading" aria-busy="true">
        <p className="section-kicker">Why you match</p>
        <p>Writing your compatibility summary…</p>
      </div>
    )
  }

  return (
    <div className="compatibility-box">
      <p className="section-kicker">Why you match</p>
      <h3>{data.headline}</h3>
      <p className="narrative-summary">{data.summary}</p>

      <div className="compatibility-bars">
        {data.dimensions.map((d) => (
          <div key={d.label}>
            <span>
              <b>{d.label}</b>
              <small>{d.score}%</small>
            </span>
            <i>
              <i style={{ width: `${d.score}%` }} />
            </i>
          </div>
        ))}
      </div>

      <div className="narrative-cols">
        <div>
          <h4>Where you align</h4>
          <ul>
            {data.strengths.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </div>
        <div>
          <h4>Worth talking about</h4>
          <ul>
            {data.frictions.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        </div>
      </div>

      <h4>Conversation starters</h4>
      <ul className="narrative-starters">
        {data.starters.map((s) => (
          <li key={s}>{s}</li>
        ))}
      </ul>

      <p className="narrative-source">
        {data.source === "ai"
          ? "Generated by AI from your quiz answers. The match score itself is a weighted calculation, not AI."
          : "Rule-based preview from your quiz answers — an AI-written narrative plugs in here. The match score is a weighted calculation, not AI."}
      </p>
    </div>
  )
}
