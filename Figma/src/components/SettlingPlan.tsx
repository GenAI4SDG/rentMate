import { useEffect, useMemo, useState } from "react"
import { genai, type PlanPhase, type SettlingPlan as Plan } from "../lib/genai"

const DONE_KEY = "rentmate_plan_done"
const PHASES: PlanPhase[] = ["Before you land", "First week", "First month"]

function loadDone(): string[] {
  try {
    const raw = localStorage.getItem(DONE_KEY)
    const parsed = raw ? JSON.parse(raw) : []
    return Array.isArray(parsed) ? parsed : []
  } catch {
    return []
  }
}

export default function SettlingPlan({
  answers,
  onFindFlats,
  onOpenMessages,
}: {
  answers: number[]
  onFindFlats: () => void
  onOpenMessages: () => void
}) {
  const [plan, setPlan] = useState<Plan | null>(null)
  const [done, setDone] = useState<string[]>(loadDone)

  useEffect(() => {
    let alive = true
    genai.settlingPlan(answers).then((p) => alive && setPlan(p))
    return () => {
      alive = false
    }
  }, [answers])

  function toggle(id: string) {
    setDone((current) => {
      const next = current.includes(id)
        ? current.filter((x) => x !== id)
        : [...current, id]
      try {
        localStorage.setItem(DONE_KEY, JSON.stringify(next))
      } catch {
        /* ignore */
      }
      return next
    })
  }

  const progress = useMemo(() => {
    if (!plan) return 0
    return Math.round((done.filter((id) => plan.steps.some((s) => s.id === id)).length / plan.steps.length) * 100)
  }, [plan, done])

  return (
    <section className="plan-screen">
      <header className="plan-hero">
        <div>
          <p className="section-kicker">Settling-in plan</p>
          <h1>
            Your first month in <em>Hong Kong.</em>
          </h1>
          <p>{plan?.summary ?? "Building your plan…"}</p>
        </div>
        <div className="plan-progress" aria-label={`${progress}% complete`}>
          <b>{progress}%</b>
          <span>done</span>
          <i>
            <i style={{ width: `${progress}%` }} />
          </i>
        </div>
      </header>

      {!plan ? (
        <p className="field-message">Generating your checklist…</p>
      ) : (
        <div className="plan-phases">
          {PHASES.map((phase) => (
            <div key={phase} className="plan-phase">
              <h2>{phase}</h2>
              {plan.steps
                .filter((s) => s.phase === phase)
                .map((step) => (
                  <label
                    key={step.id}
                    className={`plan-step ${done.includes(step.id) ? "done" : ""}`}
                  >
                    <input
                      type="checkbox"
                      checked={done.includes(step.id)}
                      onChange={() => toggle(step.id)}
                    />
                    <span>
                      <b>{step.title}</b>
                      <small>{step.detail}</small>
                      {step.id === "chat-matches" || step.id === "meetup" ? (
                        <button
                          type="button"
                          className="plan-link"
                          onClick={(e) => {
                            e.preventDefault()
                            onOpenMessages()
                          }}
                        >
                          Open messages →
                        </button>
                      ) : null}
                      {step.id === "districts" ? (
                        <button
                          type="button"
                          className="plan-link"
                          onClick={(e) => {
                            e.preventDefault()
                            onFindFlats()
                          }}
                        >
                          Browse the map →
                        </button>
                      ) : null}
                    </span>
                  </label>
                ))}
            </div>
          ))}
        </div>
      )}

      <p className="narrative-source">
        {plan?.source === "ai"
          ? "Generated by AI from your quiz answers."
          : "Rule-based plan from your quiz answers — an AI-written version plugs in here."}{" "}
        General orientation only, not legal advice.
      </p>
    </section>
  )
}
